def main(out_dir: str = "docs/marketing") -> list[Path]:
    site = _load("content/settings/site.yml")
    branches = _load("content/settings/branches.yml") if (ROOT / "content/settings/branches.yml").exists() else []
    listings = _load("content/settings/listings.yml")
    policy = _load("content/settings/rental_policy.yml")
    faq = _load("content/pages/faq.yml")
    out = Path(out_dir)
    if not out.is_absolute():
        out = ROOT / out
    out.mkdir(parents=True, exist_ok=True)
    files = {"LISTINGS_PACK.md": listings_pack(site, branches, listings, policy, faq),
             "UTM_CONVENTIONS.md": utm_conventions(),
             "REVIEW_REQUEST_TEMPLATES.md": review_templates(branches),
             "OWNER_STEPS.md": owner_steps()}
    paths = []
    for name, text in files.items():
        p = out / name
        p.write_text(text, encoding="utf-8")
        paths.append(p)
    return paths


if __name__ == "__main__":
    for p in main(*(sys.argv[1:2])):
        print(p.relative_to(ROOT) if p.is_relative_to(ROOT) else p)
