def review_templates(branches) -> str:
    maps = ((branches or [{}])[0].get("maps") or {})
    out = ["# Review request templates (WhatsApp, after the car is returned)", "",
           "Rules: ask once, never offer anything in return, never write a review for a customer.",
           "Links fill in automatically once `content/settings/branches.yml → maps` is set.", ""]
    for lang in LANGS:
        text, link = REVIEW_TEXT[lang]
        link = (link.replace("{google}", maps.get("google") or "{google}")
                    .replace("{yandex}", maps.get("yandex") or "{yandex}")
                    .replace("{twogis}", maps.get("twogis") or "{twogis}"))
        out += [f"## {lang}", "", text, link, ""]
    return "\n".join(out)


