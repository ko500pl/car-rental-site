#!/usr/bin/env python3
"""Generate docs/marketing/: map-listing pack, UTM rules, review-request
templates and the owner's click-by-click steps.

Every fact comes from a content file (site.yml, branches.yml, listings.yml,
rental_policy.yml, pages/faq.yml), so rerunning this after any edit keeps the
listings identical to the website. Usage: python scripts/make_marketing_pack.py
"""
from __future__ import annotations

import glob
import re
import sys
from pathlib import Path
from urllib.parse import urlencode

import yaml

ROOT = Path(__file__).resolve().parents[1]
LANGS = ("ka", "en", "ru", "fa", "he", "ar")
SITE_URL = "https://rentup.ge"
SOURCES = {"gbp", "yandex-maps", "2gis", "apple-maps", "localrent", "discovercars"}
MEDIUMS = {"maps", "aggregator", "referral"}  # no paid channels: owner decision 2026-10-17
PLATFORMS = (("gbp", "Google Business Profile"), ("yandex-maps", "Yandex Business"),
             ("2gis", "2GIS"), ("apple-maps", "Apple Business Connect"))
FA_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def _load(rel: str):
    return yaml.safe_load((ROOT / rel).read_text(encoding="utf-8")) or {}


def utm_url(path: str, source: str, medium: str, campaign: str = "") -> str:
    """Absolute rentup.ge URL tagged with the agreed UTM vocabulary only."""
    ok_source = source in SOURCES or re.fullmatch(r"partner-[a-z0-9-]+", source)
    if not ok_source:
        raise ValueError(f"utm_source not in the agreed vocabulary: {source!r}")
    if medium not in MEDIUMS:
        raise ValueError(f"utm_medium not in the agreed vocabulary: {medium!r}")
    q = {"utm_source": source, "utm_medium": medium}
    if campaign:
        q["utm_campaign"] = campaign
    return SITE_URL + path + "?" + urlencode(q)


def _published_places() -> int:
    n = 0
    for f in glob.glob(str(ROOT / "content/attractions/*.yml")):
        d = yaml.safe_load(Path(f).read_text(encoding="utf-8")) or {}
        if d.get("status") in (None, "published") and not d.get("draft"):
            n += 1
    return n


def descriptions(listings: dict, site: dict) -> dict:
    fleet, places = str(site["fleet_size"]), str(_published_places())
    out = {}
    for lang in LANGS:
        f, p = (fleet.translate(FA_DIGITS), places.translate(FA_DIGITS)) if lang == "fa" else (fleet, places)
        text = " ".join(listings["description"][lang].split()).replace("{fleet}", f).replace("{places}", p)
        if len(text) > 750:
            raise ValueError(f"{lang} description is {len(text)} characters (limit 750)")
        out[lang] = text
    return out


def service_lines(policy: dict) -> list[str]:
    d, ow = policy["delivery"], policy["one_way"]
    lines = ["Office pickup: free" if d.get("office_pickup_free") else None,
             "City delivery in Tbilisi: free" if "tbilisi" in (d.get("city_delivery_free_in") or []) else None]
    names = {"tbilisi-airport": "Tbilisi airport", "kutaisi-airport": "Kutaisi airport",
             "batumi-airport": "Batumi airport"}
    for key, fee in (d.get("airport_fee_gel") or {}).items():
        if fee is not None:
            lines.append(f"{names.get(key, key)} delivery: {fee} GEL")
    for key, fee in (d.get("city_fee_gel") or {}).items():
        lines.append(f"{key.title()} city delivery: {fee} GEL")
    lines.append(f"Night delivery/return {d['night_from']}–{d['night_to']}: +{d['night_surcharge_gel']} GEL")
    if ow.get("available"):
        lines.append(f"One-way between Tbilisi, Kutaisi and Batumi: {ow['fee_gel']} GEL")
    lines.append("Rental with a driver: available")
    lines.append("Insurance: CDW included in the price")
    return [x for x in lines if x]


def faq_items(faq: dict, lang: str, n: int) -> list[tuple[str, str]]:
    items = []
    for block in faq[lang].get("blocks", []):
        if block.get("type") == "faq":
            items += [(i["q"], i["a"]) for i in block.get("items", [])]
    return items[:n]


def listings_pack(site, branches, listings, policy, faq) -> str:
    desc = descriptions(listings, site)
    out = ["# Map listings pack", "",
           "_Generated by `scripts/make_marketing_pack.py` — do not edit by hand; edit the source YAML and rerun._", ""]
    for b in branches or []:
        a = b["address"]["en"]
        for src, label in PLATFORMS:
            out += [f"## {label} — {a['street']}, {a['city']}", "",
                    "**Name:** RentUp", f"**Category:** {listings['category']}",
                    f"**Address:** {a['street']}, {a['city']} {b['zip']}, Georgia",
                    f"**Coordinates:** {b['lat']}, {b['lon']}",
                    f"**Hours:** every day {b['opens']}–{b['closes']}",
                    f"**Phone / WhatsApp:** {b['phone_e164']}",
                    f"**Website link:** {utm_url('/', src, 'maps', b['id'])}", "",
                    "**Services:**"] + [f"- {x}" for x in service_lines(policy)] + [""]
    out += ["## Descriptions (paste per language)", ""]
    for lang in LANGS:
        out += [f"### {lang} ({len(desc[lang])}/750)", "", desc[lang], ""]
    out += ["## Questions & answers (seed per language)", ""]
    for lang in LANGS:
        out += [f"### {lang}", ""]
        for q, a in faq_items(faq, lang, int(listings.get("faq_count", 10))):
            out += [f"**{q}**", "", " ".join(str(a).split()), ""]
    return "\n".join(out)


def utm_conventions() -> str:
    rows = [("gbp", "maps"), ("yandex-maps", "maps"), ("2gis", "maps"), ("apple-maps", "maps"),
            ("localrent", "aggregator"), ("discovercars", "aggregator"),
            ("partner-<slug>", "referral")]
    out = ["# UTM conventions", "",
           "Use only these values — the analytics reports group by them.", "",
           "| utm_source | utm_medium | Example |", "|---|---|---|"]
    for src, med in rows:
        ex_src = src.replace("<slug>", "hotel-example")
        out.append(f"| `{src}` | `{med}` | {utm_url('/', ex_src, med)} |")
    out += ["", "`utm_campaign` is free text (branch id, partner name).",
            "No paid-ads values: the programme runs on a zero budget (owner decision 2026-10-17).", ""]
    return "\n".join(out)


